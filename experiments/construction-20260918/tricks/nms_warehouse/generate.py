#!/usr/bin/env python3
"""Generate the isolated warehouse lane asset by running unmodified NMS source on GRID."""
import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / 'tools'))
from cpu_resources import cpu_resources


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write(path, data):
    path.write_text(json.dumps(data, indent=2) + '\n')


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--execute', action='store_true')
    a = p.parse_args()
    out = a.output.resolve()
    src = ROOT / 'nms/Solution'
    native = [src / ('Objects/' + name) for name in [
        'Environment/graph_guidance.cpp', 'Environment/map.cpp',
        'Environment/info.cpp', 'Basic/position.cpp']]
    map_path = ROOT / 'mr24/warehouse.domain/maps/warehouse_large.map'
    paths = native + list(src.rglob('*.hpp')) + list((ROOT / 'nms/inc').rglob('*.h'))
    paths += [HERE / 'dump_native.cpp', Path(__file__).resolve(), map_path]
    source_hashes = {str(x.relative_to(ROOT)): sha(x) for x in paths}
    if not a.execute:
        out.mkdir(parents=True, exist_ok=False)
        write(out / 'request.json', {'sources': source_hashes})
        cmd = ['/usr/bin/python3', str(Path(__file__).resolve()), '--execute', '--output', str(out)]
        (out / 'job.sh').write_text('#!/bin/bash\nset -eu\nexec ' + ' '.join(map(shlex.quote, cmd)) + '\n')
        submit = ['qsub', '-terse', '-w', 'e', '-cwd', '-q', 'debian.q', '-pe', 'threaded', '1',
                  '-binding', 'linear:1', '-l', 'exclusive=true,h_rt=00:10:00,h_vmem=4G',
                  '-m', 'n', '-N', 'nms_lane_asset', '-j', 'y', '-o', str(out / 'job.log'),
                  '-S', '/bin/bash', str(out / 'job.sh')]
        result = subprocess.run(submit, cwd=str(ROOT), text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        write(out / 'submission.json', {'command': submit, 'returncode': result.returncode, 'response': result.stdout})
        print(result.stdout, end='')
        return result.returncode
    assert source_hashes == json.loads((out / 'request.json').read_text())['sources']
    resources = cpu_resources()
    assert int(os.environ['NSLOTS']) >= 1 and resources['representative_cpus']
    assert resources['effective_cpu_quota'] is None or resources['effective_cpu_quota'] >= 1
    write(out / 'allocation.json', resources)
    compiler = ROOT / 'env/bin/x86_64-conda-linux-gnu-c++'
    command = [str(compiler), '-std=c++17', '-O2', '-ffunction-sections', '-fdata-sections',
               '-Wl,--gc-sections', '-I' + str(src), '-I' + str(ROOT / 'nms/inc'),
               '-isystem', str(ROOT / 'env/include'), str(HERE / 'dump_native.cpp')]
    command += list(map(str, native)) + ['-o', str(out / 'dump_native')]
    subprocess.run(command, check=True, cwd=str(ROOT))
    with (out / 'native-forward.txt').open('w') as stream:
        subprocess.run([str(out / 'dump_native'), str(map_path)], check=True, stdout=stream)
    data = (out / 'native-forward.txt').read_text().splitlines()
    rows, cols = map(int, data[0].split())
    assert (rows, cols) == (140, 500) and len(data) == rows * cols + 1
    text_map = ''.join(map_path.read_text().splitlines()[4:])
    masks, field, occupancy = [], [], []
    for cell, line in enumerate(data[1:]):
        weights = list(map(int, line.split()))
        assert len(weights) == 4
        wall = text_map[cell] in '@T'
        occupancy.append(int(wall))
        assert all(x == 0 for x in weights) if wall else all(x in (20, 21, 200, 201) for x in weights)
        masks.append('x' if wall else format(sum(1 << d for d, x in enumerate(weights) if x >= 200), 'x'))
        field.extend(4 if wall or x < 200 else 16 for x in weights)
    assert occupancy.count(0) == 38586
    header = ['#pragma once', '// Generated by experiments/construction-20260918/tricks/nms_warehouse/generate.py.',
              '// TRICK: native NMS lane directions, adapted forward costs4/16; bands omitted.',
              'namespace cgar { namespace tricks {',
              'inline constexpr int warehouse_rows = 140, warehouse_cols = 500, warehouse_free = 38586;',
              'inline constexpr char warehouse_map_sha256[] = "' + sha(map_path) + '";',
              'inline constexpr char warehouse_occupancy_sha256[] = "' + hashlib.sha256(bytes(occupancy)).hexdigest() + '";',
              'inline constexpr char warehouse_field_sha256[] = "' + hashlib.sha256(bytes(field)).hexdigest() + '";',
              'inline constexpr char warehouse_masks[] =']
    encoded = ''.join(masks)
    header += ['    "' + encoded[k:k + 100] + '"' for k in range(0, len(encoded), 100)]
    header += ['    ;', 'static_assert(sizeof(warehouse_masks) == 140 * 500 + 1, "warehouse asset size");', '}}', '']
    (out / 'warehouse_lanes.hpp').write_text('\n'.join(header))
    write(out / 'generation.json', {'completed_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
          'track': 'TRICK', 'activation': '--trick WAREHOUSE', 'native_source_unchanged': True,
          'compiler_command': command, 'native_binary_sha256': sha(out / 'dump_native'),
          'native_dump_sha256': sha(out / 'native-forward.txt'), 'generated_header_sha256': sha(out / 'warehouse_lanes.hpp'),
          'field_sha256': hashlib.sha256(bytes(field)).hexdigest(), 'map_sha256': sha(map_path),
          'rows': rows, 'cols': cols, 'free_cells': occupancy.count(0), 'direction_offsets': [1, cols, -1, -cols],
          'adaptation': '20/21 -> 4; 200/201 -> 16; walls -> unused4; turns remain CGAR4; coordinate bands omitted'})
    assert source_hashes == {str(x.relative_to(ROOT)): sha(x) for x in paths}
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
