#!/usr/bin/env python3
"""Hash bounded blends of the already verified NMS/KK RANDOM forward fields."""
import datetime,hashlib,json,pathlib,re
ROOT=next(p for p in pathlib.Path(__file__).resolve().parents if (p/'cgar/tricks/random_reference.hpp').is_file())
def fnv(values):
 value=14695981039346656037
 for item in values:value=((value^item)*1099511628211)&((1<<64)-1)
 return value
def main():
 source=ROOT/'cgar/tricks/random_reference.hpp';text=source.read_text();records=[]
 header=['#pragma once','#include <cstdint>','// Generated by experiments/allmaps-20260920/reference-strength/generate.py.', '// Explicit RANDOM instance trick; immutable hashes for blends toward uniform20.', 'namespace cgar { namespace tricks {','struct ReferenceContrastIdentity { const char* sha256; uint64_t fnv1a64; };']
 for name in ['random_nms','random_kk02','random_kk03','random_kk04']:
  match=re.search(r'inline constexpr uint8_t '+name+r'_forward\[\]\s*=\s*\{([^}]+)\}',text,re.S);assert match,name
  values=list(map(int,re.findall(r'\d+',match.group(1))));assert len(values)==4096 and all(1<=x<=200 for x in values)
  sha=hashlib.sha256(bytes(values)).hexdigest();fingerprint=fnv(values)
  assert re.search(name+r'_native_nobands_field_sha256\[\] = "'+sha+'"',text)
  assert re.search(name+r'_native_nobands_fnv1a64 = '+str(fingerprint)+r'ULL',text)
  fields=[]
  for strength in [25,50,75]:
   # Nonnegative weighted mean; round to nearest integer, ties upward.
   blend=[(20*(100-strength)+x*strength+50)//100 for x in values]
   assert all(min(20,x)<=y<=max(20,x) and (x!=20 or y==20) for x,y in zip(values,blend))
   digest=hashlib.sha256(bytes(blend)).hexdigest();fp=fnv(blend);assert digest!=sha
   symbol=name+'_contrast'+str(strength)+'_native_nobands'
   header+=['inline constexpr char '+symbol+'_field_sha256[] = "'+digest+'";','inline constexpr uint64_t '+symbol+'_fnv1a64 = '+str(fp)+'ULL;']
   fields.append(dict(strength=strength,sha256=digest,fnv1a64=fp,minimum=min(blend),maximum=max(blend),values_checked=len(blend)))
  header+=['inline constexpr ReferenceContrastIdentity '+name+'_contrasts[] = {']+['    {'+name+'_contrast'+str(s)+'_native_nobands_field_sha256, '+name+'_contrast'+str(s)+'_native_nobands_fnv1a64},' for s in [25,50,75]]+['};']
  assert [(20*(100-100)+x*100+50)//100 for x in values]==values
  records.append(dict(provider=name,original_sha256=sha,original_fnv1a64=fingerprint,strength100_identity=True,fields=fields))
 header+=['}}',''];dest=ROOT/'cgar/tricks/random_reference_contrast.hpp';dest.write_text('\n'.join(header))
 report=dict(generated_utc=datetime.datetime.now(datetime.timezone.utc).isoformat(),source=str(source.relative_to(ROOT)),source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),header_sha256=hashlib.sha256(dest.read_bytes()).hexdigest(),formula='round_half_up(20 + strength/100 * (original-20))',geometry_unchanged=True,original_fields_previously_verified='../random-reference/generation-v1/generation.json',records=records)
 (pathlib.Path(__file__).resolve().parent/'generation.json').write_text(json.dumps(report,indent=2)+'\n');print('Verified',len(records)*3*4096,'transformed forward values and all four original hashes')
if __name__=='__main__':main()
